export const textWidth = (str, scale = 1, tracking = 1) => str.length * (GLYPH_W + tracking) * scale;

/** Draw text into an RGBA buffer. Unknown characters are skipped rather than throwing. */
export function drawText(buf, bufW, str, x, y, colour, scale = 1, tracking = 1) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(colour.slice(i, i + 2), 16));
  let cx = x;
  for (const raw of str.toUpperCase()) {
    const glyph = G[raw];
    if (glyph) {
      glyph.forEach((row, gy) => [...row].forEach((px, gx) => {
        if (px !== '#') return;
        for (let dy = 0; dy < scale; dy++) for (let dx = 0; dx < scale; dx++) {
          const px0 = cx + gx * scale + dx, py0 = y + gy * scale + dy;
          if (px0 < 0 || py0 < 0 || px0 >= bufW) continue;
          const i = (py0 * bufW + px0) * 4;
          if (i + 3 >= buf.length) continue;
          buf[i] = r; buf[i + 1] = g; buf[i + 2] = b; buf[i + 3] = 255;
        }
      }));
    }
    cx += (GLYPH_W + tracking) * scale;
  }
}
